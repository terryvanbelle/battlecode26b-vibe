#!/usr/bin/env python3
"""Progress charts as standalone SVG (no plotting library on the driver).

  plot_progress.py [--tsv research/progress.tsv] [--out progress/]

research/progress.tsv columns: version, date (PDT, YYYY-MM-DD HH:MM), metric, value. One row per measurement.
Each metric becomes one series; every chart plots value against version order (first appearance in the file).
Writes progress/<metric-group>.svg and progress/index.md listing the charts.
Metric groups: the part of the metric name before the first '.', e.g. win.example and win.field share 'win'.
"""
import argparse, collections, html, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLORS = ['#2a6fdb', '#d9480f', '#2b8a3e', '#7048e8', '#c2255c', '#0b7285', '#5c940d', '#495057']


def load(path):
    versions, series = [], collections.OrderedDict()
    for line in open(path):
        if not line.strip() or line.startswith('#') or line.startswith('version\t'):
            continue
        v, _date, metric, value = line.rstrip('\n').split('\t')[:4]
        if v not in versions:
            versions.append(v)
        series.setdefault(metric, {})[v] = float(value)
    return versions, series


def svg_chart(title, versions, series, w=720, h=360):
    pad_l, pad_r, pad_t, pad_b = 56, 160, 36, 70
    xs = {v: i for i, v in enumerate(versions)}
    vals = [y for s in series.values() for y in s.values()]
    lo, hi = min(vals + [0.0]), max(vals + [1.0])
    if hi == lo:
        hi = lo + 1
    pw, ph = w - pad_l - pad_r, h - pad_t - pad_b
    X = lambda i: pad_l + (pw * i / max(1, len(versions) - 1))
    Y = lambda y: pad_t + ph - ph * (y - lo) / (hi - lo)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="sans-serif" font-size="11">',
           f'<rect width="{w}" height="{h}" fill="white"/>',
           f'<text x="{pad_l}" y="20" font-size="14" font-weight="bold">{html.escape(title)}</text>']
    for k in range(5):
        y = lo + (hi - lo) * k / 4
        out.append(f'<line x1="{pad_l}" x2="{pad_l + pw}" y1="{Y(y):.1f}" y2="{Y(y):.1f}" stroke="#e9ecef"/>')
        out.append(f'<text x="{pad_l - 6}" y="{Y(y) + 4:.1f}" text-anchor="end" fill="#495057">{y:.3g}</text>')
    for v, i in xs.items():
        out.append(f'<text transform="translate({X(i):.1f},{pad_t + ph + 12}) rotate(40)" fill="#495057">{html.escape(v)}</text>')
    for n, (name, s) in enumerate(series.items()):
        c = COLORS[n % len(COLORS)]
        pts = [(X(xs[v]), Y(s[v])) for v in versions if v in s]
        if len(pts) > 1:
            out.append(f'<polyline fill="none" stroke="{c}" stroke-width="2" points="' +
                       ' '.join(f'{x:.1f},{y:.1f}' for x, y in pts) + '"/>')
        for x, y in pts:
            out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3" fill="{c}"/>')
        ly = pad_t + 14 * n
        out.append(f'<rect x="{pad_l + pw + 12}" y="{ly}" width="10" height="10" fill="{c}"/>')
        out.append(f'<text x="{pad_l + pw + 26}" y="{ly + 9}">{html.escape(name)}</text>')
    out.append('</svg>')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tsv', default=os.path.join(REPO, 'research', 'progress.tsv'))
    ap.add_argument('--out', default=os.path.join(REPO, 'progress'))
    o = ap.parse_args()
    versions, series = load(o.tsv)
    groups = collections.OrderedDict()
    for m, s in series.items():
        groups.setdefault(m.split('.')[0], collections.OrderedDict())[m] = s
    os.makedirs(o.out, exist_ok=True)
    idx = ['# Progress charts', '', 'Generated by tools/plot_progress.py from research/progress.tsv.', '']
    for g, ss in groups.items():
        open(os.path.join(o.out, f'{g}.svg'), 'w').write(svg_chart(g, versions, ss))
        idx += [f'## {g}', '', f'![{g}]({g}.svg)', '']
    open(os.path.join(o.out, 'index.md'), 'w').write('\n'.join(idx))
    print(f'{len(groups)} charts, {len(versions)} versions -> {o.out}')


if __name__ == '__main__':
    main()
